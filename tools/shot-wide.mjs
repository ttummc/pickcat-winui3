import fs from "node:fs";
const list = await (await fetch("http://127.0.0.1:9444/json/list")).json();
const page = list.find(x => x.url.includes("pickcat"));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m.result); pending.delete(m.id); } };
await new Promise(r => ws.onopen = r);
const send = (method, params = {}) => new Promise(r => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
await send("Page.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1120, height: 720, deviceScaleFactor: 1, mobile: false });
await new Promise(r => setTimeout(r, 1200));
const m = await send("Runtime.evaluate", { expression: `JSON.stringify({w: innerWidth, rail: Math.round(document.querySelector('.pc-dsh-rail').getBoundingClientRect().width), main: Math.round(document.querySelector('.pc-dsh-main').getBoundingClientRect().width), overflowX: document.documentElement.scrollWidth > innerWidth})`, returnByValue: true });
console.log(m.result.value);
const shot = await send("Page.captureScreenshot", { format: "png" });
fs.writeFileSync("docs/_dsh-wide.png", Buffer.from(shot.data, "base64"));
console.log("saved");
ws.close();
