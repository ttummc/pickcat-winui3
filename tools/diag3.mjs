import { connectBrowser, connectWs, sleep } from "./cdp.mjs";
const browser = await connectBrowser();
const t = await browser.send("Target.createTarget", { url: "about:blank" });
await sleep(1200);
const list = await (await fetch("http://127.0.0.1:9333/json/list")).json();
const ws = await connectWs(list.find(x => x.id === t.targetId).webSocketDebuggerUrl);
const msgs = [];
ws.on("Runtime.consoleAPICalled", p => msgs.push(`[${p.type}] ` + (p.args ?? []).map(a => a.value ?? a.description ?? "").join(" ").slice(0, 300)));
ws.on("Runtime.exceptionThrown", p => msgs.push(`[exception] ${(p.exceptionDetails?.exception?.description ?? p.exceptionDetails?.text ?? "").slice(0, 400)}`));
ws.on("Log.entryAdded", p => msgs.push(`[log.${p.entry.level}] ${p.entry.text.slice(0, 200)}`));
await ws.send("Runtime.enable");
await ws.send("Log.enable");
await ws.send("Page.enable");
await ws.send("Page.navigate", { url: "https://pickcat.dao3.fun/#/" });
await sleep(7000);
console.log(msgs.slice(0, 20).join("\n") || "(无消息)");
const r = await ws.send("Runtime.evaluate", { expression: "document.getElementById('pickcat-root')?.innerHTML.slice(0,150)", returnByValue: true });
console.log("root:", r.result.value);
ws.close(); browser.close();
